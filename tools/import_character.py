#!/usr/bin/env python3
"""Import CombatBot characters into Marine Commander.

The script reads the newest snapshot for each named character from CombatBot's
SQLite character database, maps the melee-relevant stats into Marine Commander's
token format, and writes/merges them into js/characters.js.

Examples:
    python3 tools/import_character.py Karen Salmon Ella Amber
    python3 tools/import_character.py --db ~/git/CombatBot/resources/characters.db Karen
    python3 tools/import_character.py --img-dir assets/tokens/player Beagle Ella Karen
    python3 tools/import_character.py --weapon laser_rifle --no-default-kit Ella
"""

from __future__ import annotations

import argparse
import json
import math
import re
import sqlite3
import sys
from pathlib import Path
from typing import NoReturn

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUT = ROOT / "js" / "characters.js"
DEFAULT_DB_CANDIDATES = (
    Path.home() / "git" / "CombatBot" / "resources" / "characters.db",
    Path.home() / "git" / "Combatbot" / "resources" / "characters.db",
    Path.home() / "work" / "git" / "CombatBot" / "resources" / "characters.db",
    Path.home() / "work" / "git" / "Combatbot" / "resources" / "characters.db",
)
DEFAULT_KIT = (
    {"name": "Laser cell", "qty": 2},
    {"name": "Medkit", "qty": 1},
)
DEFAULT_WEAPON = "laser_rifle"
WEAPON_KEYS = (
    "", "knife", "stick", "club", "sword", "stunrod",
    "laser", "mass_driver", "rifle", "laser_rifle",
)
PALETTE = (
    "#5ec8e5", "#f07a5a", "#f2c14e", "#9b8cff",
    "#58d68a", "#ff8fa3", "#6aa6ff", "#3cc4b1",
)
IMAGE_EXTENSIONS = (".png", ".webp", ".jpg", ".jpeg", ".gif")
HEADER = """/* Generated by tools/import_character.py.
 * Source: CombatBot resources/characters.db (latest snapshot per character).
 * Re-run the importer instead of editing this file by hand.
 */
"""


def fail(message: str) -> NoReturn:
    print("error: " + message, file=sys.stderr)
    raise SystemExit(1)


def locate_db(requested: str | None) -> Path:
    if requested:
        path = Path(requested).expanduser()
        if not path.is_file():
            fail(f"character database not found: {path}")
        return path
    for path in DEFAULT_DB_CANDIDATES:
        if path.is_file():
            return path
    tried = "\n  ".join(str(p) for p in DEFAULT_DB_CANDIDATES)
    fail("could not find CombatBot's characters.db. Tried:\n  " + tried +
         "\nPass --db /path/to/characters.db")


def clean_text(value) -> str:
    text = str(value if value is not None else "").strip()
    if text.lower() in {"", "none", "null", "$placeholder"}:
        return ""
    # CombatBot has some names stored as UTF-8 that was decoded as Latin-1
    # (for example "AldevarÃ©z"). Repair the common double-encoding pattern.
    if any(marker in text for marker in ("Ã", "Â", "â€")):
        try:
            repaired = text.encode("latin-1").decode("utf-8")
        except (UnicodeEncodeError, UnicodeDecodeError):
            pass
        else:
            if repaired != text:
                text = repaired
    return text


def numeric(value, *, maximum: int = 50) -> int:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return 0
    if not math.isfinite(number):
        return 0
    return max(0, min(maximum, int(round(number))))


def display_name(callsign: str, first: str, last: str) -> str:
    if first and last:
        return f"{first} '{callsign}' {last}"
    if last:
        return f"{callsign} {last}"
    if first and first.casefold() != callsign.casefold():
        return f"{first} '{callsign}'"
    return callsign


def resolve_character(connection: sqlite3.Connection, query: str):
    base = """
        SELECT id, callsign, first_name, last_name, rank, branch, occupation
        FROM characters
    """
    exact = connection.execute(
        base + " WHERE lower(callsign) = lower(?)", (query,)
    ).fetchall()
    if not exact:
        exact = connection.execute(
            base + """
            WHERE lower(trim(coalesce(first_name, '') || ' ' || coalesce(last_name, ''))) = lower(?)
               OR lower(trim(coalesce(callsign, '') || ' ' || coalesce(first_name, '') || ' ' || coalesce(last_name, ''))) = lower(?)
            """,
            (query, query),
        ).fetchall()
    if not exact:
        like = "%" + query.casefold() + "%"
        exact = connection.execute(
            base + """
            WHERE lower(callsign) LIKE ?
               OR lower(coalesce(first_name, '')) LIKE ?
               OR lower(coalesce(last_name, '')) LIKE ?
               OR lower(trim(coalesce(first_name, '') || ' ' || coalesce(last_name, ''))) LIKE ?
            ORDER BY callsign
            """,
            (like, like, like, like),
        ).fetchall()
    if not exact:
        fail(f"no character matched {query!r}")
    if len(exact) > 1:
        # The database can contain duplicate callsign rows (for example a
        # renamed/corrected duplicate with no snapshots). Prefer the row that
        # has the newest saved character state.
        scored = []
        for row in exact:
            checkpoint = latest_checkpoint(connection, row[0])
            if checkpoint is not None:
                scored.append((checkpoint, row))
        if len(scored) == 1:
            return scored[0][1]
        if scored:
            scored.sort(key=lambda item: item[0], reverse=True)
            if scored[0][0] != scored[1][0]:
                return scored[0][1]
        names = ", ".join(f"{row[1]} (id {row[0]})" for row in exact)
        fail(f"{query!r} is ambiguous; matched: {names}")
    return exact[0]


def latest_checkpoint(connection: sqlite3.Connection, character_id: int):
    row = connection.execute(
        "SELECT max(checkpoint_id) FROM character_snapshots WHERE character_id = ?",
        (character_id,),
    ).fetchone()
    return row[0] if row else None


def latest_snapshot(connection: sqlite3.Connection, character_id: int):
    row = connection.execute(
        """
        SELECT cs.snapshot_json, cp.created_at
        FROM character_snapshots cs
        JOIN checkpoints cp ON cp.id = cs.checkpoint_id
        WHERE cs.character_id = ?
        ORDER BY cs.checkpoint_id DESC, cs.id DESC
        LIMIT 1
        """,
        (character_id,),
    ).fetchone()
    if row is None:
        fail(f"character id {character_id} has no saved snapshots")
    try:
        snapshot = json.loads(row[0])
    except json.JSONDecodeError as exc:
        fail(f"character id {character_id} has invalid snapshot JSON: {exc}")
    return snapshot, row[1]


def skill_number(skills: dict, *names: str) -> int:
    lowered = {str(key).strip().casefold(): value for key, value in skills.items()}
    for name in names:
        if name.casefold() in lowered:
            return numeric(lowered[name.casefold()])
    return 0


def find_portrait(image_dir: Path, callsign: str) -> str:
    if not image_dir.is_dir():
        fail(f"portrait directory not found: {image_dir}")
    matches = []
    for path in image_dir.iterdir():
        if not path.is_file() or path.name.endswith("~"):
            continue
        if path.suffix.casefold() not in IMAGE_EXTENSIONS:
            continue
        if path.stem.casefold() == callsign.casefold():
            matches.append(path)
    if not matches:
        return ""
    matches.sort(key=lambda path: (IMAGE_EXTENSIONS.index(path.suffix.casefold()), path.name.casefold()))
    try:
        return matches[0].resolve().relative_to(ROOT).as_posix()
    except ValueError:
        fail(f"portrait {matches[0]} must be inside the Marine Commander repository")


def import_inventory(raw_inventory, *, include_default_kit: bool):
    bag = []
    by_name = {}

    def add(name: str, qty) -> None:
        name = clean_text(name)
        quantity = numeric(qty, maximum=999)
        if not name or quantity <= 0:
            return
        key = name.casefold()
        if key in by_name:
            by_name[key]["qty"] = min(999, by_name[key]["qty"] + quantity)
            return
        item = {"name": name[:36], "qty": quantity}
        by_name[key] = item
        bag.append(item)

    if include_default_kit:
        for item in DEFAULT_KIT:
            add(item["name"], item["qty"])
    if isinstance(raw_inventory, dict):
        for name, qty in raw_inventory.items():
            if str(name).strip().casefold() == "credits":
                continue
            add(str(name), qty)
    return bag[:40]


def existing_records(path: Path) -> list[dict]:
    if not path.is_file():
        return []
    text = path.read_text(encoding="utf-8")
    if not text.strip():
        return []
    match = re.search(r"window\.MC_CHARACTERS\s*=\s*(\[.*\])\s*;\s*$", text, re.S)
    if not match:
        fail(f"{path} does not look like a generated Marine Commander character file")
    try:
        records = json.loads(match.group(1))
    except json.JSONDecodeError as exc:
        fail(f"could not parse existing characters in {path}: {exc}")
    if not isinstance(records, list):
        fail(f"existing characters in {path} are not a list")
    return [record for record in records if isinstance(record, dict)]


def pick_color(existing: list[dict]) -> str:
    used = {str(record.get("color", "")).casefold() for record in existing}
    for color in PALETTE:
        if color.casefold() not in used:
            return color
    return PALETTE[len(existing) % len(PALETTE)]


def convert(connection: sqlite3.Connection, query: str, existing: list[dict],
            *, weapon_override: str | None, include_default_kit: bool,
            image_dir: Path | None) -> dict:
    character_id, callsign, first_name, last_name, rank, branch, occupation = resolve_character(connection, query)
    snapshot, snapshot_at = latest_snapshot(connection, character_id)
    character = snapshot.get("Character") or {}
    if not isinstance(character, dict):
        fail(f"character {callsign} has no Character data in its latest snapshot")

    callsign = clean_text(character.get("Callsign")) or clean_text(callsign)
    first = clean_text(character.get("FirstName")) or clean_text(first_name)
    last = clean_text(character.get("LastName")) or clean_text(last_name)
    skills = character.get("SkillList") or {}
    if not isinstance(skills, dict):
        skills = {}
    stats = {
        "melee": skill_number(skills, "Melee"),
        "martialArts": skill_number(skills, "Martial Arts"),
        "dance": skill_number(skills, "Dance", "Dancing"),
        "athletic": numeric(character.get("Athletic")),
    }

    previous = next(
        (record for record in existing
         if str(record.get("callsign", "")).casefold() == callsign.casefold()
         or str(record.get("name", "")).casefold() == display_name(callsign, first, last).casefold()),
        None,
    )
    weapon = weapon_override or str((previous or {}).get("weapon") or DEFAULT_WEAPON)
    if weapon not in WEAPON_KEYS:
        fail(f"unknown weapon {weapon!r}; choose one of: {', '.join(k or '(unarmed)' for k in WEAPON_KEYS)}")

    descriptions = snapshot.get("Descriptions")
    description = ""
    if isinstance(descriptions, dict):
        key = clean_text(snapshot.get("CurrentDesc"))
        description = clean_text(descriptions.get(key)) if key else ""
        if not description:
            for value in descriptions.values():
                description = clean_text(value)
                if description:
                    break
    quirks = character.get("Quirks") if isinstance(character.get("Quirks"), list) else []

    image = str((previous or {}).get("img") or "")
    if image_dir is not None:
        image = find_portrait(image_dir, callsign) or image

    record = {
        "callsign": callsign,
        "name": display_name(callsign, first, last),
        "firstName": first,
        "lastName": last,
        "rank": clean_text(character.get("rank")) or clean_text(rank),
        "branch": clean_text(character.get("branch")) or clean_text(branch),
        "occupation": clean_text(character.get("occupation")) or clean_text(occupation),
        "color": str((previous or {}).get("color") or pick_color(existing)),
        "stats": stats,
        "weapon": weapon,
        "inventory": import_inventory(character.get("inventory"), include_default_kit=include_default_kit),
        "img": image,
        "quirks": [clean_text(quirk) for quirk in quirks if clean_text(quirk)],
        "description": description,
        "source": {
            "characterId": character_id,
            "snapshotAt": snapshot_at,
        },
    }
    return record


def write_characters(path: Path, records: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    text = HEADER + "window.MC_CHARACTERS = " + json.dumps(records, indent=2, ensure_ascii=False) + ";\n"
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(text, encoding="utf-8")
    temporary.replace(path)


def main() -> None:
    parser = argparse.ArgumentParser(description="Import CombatBot characters into Marine Commander.")
    parser.add_argument("names", nargs="+", help="Callsign, first/last name, or full name")
    parser.add_argument("--db", help="Path to CombatBot's resources/characters.db")
    parser.add_argument("--out", default=str(DEFAULT_OUT), help=f"Output JS file (default: {DEFAULT_OUT})")
    parser.add_argument("--img-dir", help="Directory of portraits named after each callsign (for example assets/tokens/player)")
    parser.add_argument("--weapon", choices=WEAPON_KEYS, help=f"Weapon key (default for new characters: {DEFAULT_WEAPON})")
    parser.add_argument("--no-default-kit", action="store_true", help="Do not add the default laser cells and medkit")
    args = parser.parse_args()

    db_path = locate_db(args.db)
    out_path = Path(args.out).expanduser().resolve()
    image_dir = Path(args.img_dir).expanduser().resolve() if args.img_dir else None
    if image_dir is not None and not image_dir.is_dir():
        fail(f"portrait directory not found: {image_dir}")
    records = existing_records(out_path)
    try:
        connection = sqlite3.connect(db_path.resolve().as_uri() + "?mode=ro", uri=True)
    except sqlite3.Error as exc:
        fail(f"could not open {db_path}: {exc}")
    with connection:
        for name in args.names:
            record = convert(
                connection, name, records,
                weapon_override=args.weapon,
                include_default_kit=not args.no_default_kit,
                image_dir=image_dir,
            )
            index = next(
                (i for i, item in enumerate(records)
                 if str(item.get("callsign", "")).casefold() == record["callsign"].casefold()),
                None,
            )
            if index is None:
                records.append(record)
            else:
                records[index] = record
            stats = record["stats"]
            print(
                f"Imported {record['callsign']}: {record['name']} "
                f"(melee {stats['melee']}, martial arts {stats['martialArts']}, "
                f"dance {stats['dance']}, athletic {stats['athletic']})"
            )
    connection.close()
    write_characters(out_path, records)
    print(f"Wrote {len(records)} character{'s' if len(records) != 1 else ''} to {out_path}")


if __name__ == "__main__":
    main()
